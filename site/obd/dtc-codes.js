const GROUPS = {
  P0: 'Generic powertrain', P1: 'Manufacturer-specific powertrain', P2: 'Generic powertrain', P3: 'Powertrain',
  C0: 'Generic chassis', C1: 'Manufacturer-specific chassis', B0: 'Generic body', B1: 'Manufacturer-specific body',
  U0: 'Generic network/communication', U1: 'Manufacturer-specific network/communication'
};

const P_SYSTEMS = {
  0: 'fuel and air metering / auxiliary emission controls', 1: 'fuel and air metering', 2: 'fuel and air metering (injector circuit)',
  3: 'ignition system or misfire', 4: 'auxiliary emission controls', 5: 'vehicle speed, idle control and auxiliary inputs',
  6: 'computer and output circuits', 7: 'transmission', 8: 'transmission', 9: 'transmission',
  A: 'hybrid propulsion', B: 'hybrid propulsion', C: 'hybrid propulsion'
};

export function describeDtc(code) {
  if (CODES[code]) return { text: CODES[code], known: true };
  const group = GROUPS[code.slice(0, 2)] || 'Unknown group';
  const system = code[0] === 'P' ? P_SYSTEMS[code[2]] : null;
  return { text: system ? `${group} – ${system}` : group, known: false };
}
